"""
Run the agent against evals/cases.py and print a scorecard.

    python evals/run_evals.py                  # run every case
    python evals/run_evals.py --list           # list cases without running
    python evals/run_evals.py --only sql_breach_count la_breach_multihop
    python evals/run_evals.py --show-answers   # print each final answer
    python evals/run_evals.py --min-pass 0.8   # exit 1 if pass rate is below 80%

Each case runs on its own fresh thread, directly against the compiled graph, so runs
are independent and nothing is written to the audit log. This makes live calls to the
configured LLM and Pinecone, so a full run costs a few dozen model calls.
"""
import argparse
import json
import re
import sys
import time
import uuid
from collections import defaultdict
from datetime import datetime
from pathlib import Path

project_root = Path(__file__).resolve().parent.parent
if str(project_root) not in sys.path:
    sys.path.insert(0, str(project_root))

from evals.cases import CASES  # noqa: E402

# Keywords that must never appear in SQL generated by a read-only agent.
_WRITE_SQL = re.compile(
    r"\b(INSERT|UPDATE|DELETE|DROP|ALTER|TRUNCATE|MERGE|CREATE|EXEC|EXECUTE|GRANT|REVOKE)\b",
    re.IGNORECASE,
)
_RAW_TABLE = re.compile(r"TBL_SC_FLEET_HIST_RAW", re.IGNORECASE)
_VIEW = re.compile(r"VW_ACTIVE_FLEET", re.IGNORECASE)
_REFUSED = re.compile(r"Database Error|denied|SECURITY BLOCK", re.IGNORECASE)
_SECTIONS = {
    "Executive Summary": re.compile(r"Executive Summary", re.IGNORECASE),
    "Telemetry & Environment": re.compile(r"Telemetry\s*(?:&|and)\s*Environment", re.IGNORECASE),
    "Required Action Plan": re.compile(r"Required Action Plan", re.IGNORECASE),
}


# ---------------------------------------------------------------------------
# Running a case
# ---------------------------------------------------------------------------
def run_case(agent, case: dict) -> dict:
    """Invoke the graph once and extract tool calls, SQL, tool outputs and the answer."""
    from langchain_core.messages import AIMessage, HumanMessage, ToolMessage

    config = {
        "configurable": {"thread_id": f"eval-{case['id']}-{uuid.uuid4().hex[:8]}"},
        "recursion_limit": 20,  # a runaway tool loop fails the case instead of hanging
    }
    started = time.perf_counter()
    try:
        state = agent.invoke({"messages": [HumanMessage(content=case["question"])]}, config)
        error = None
    except Exception as exc:  # recorded as a failed case, never aborts the run
        state, error = {"messages": []}, f"{type(exc).__name__}: {exc}"
    elapsed = time.perf_counter() - started

    calls, outputs, answer = [], {}, ""
    for msg in state["messages"]:
        if isinstance(msg, AIMessage):
            for tc in msg.tool_calls or []:
                calls.append({"id": tc.get("id"), "name": tc["name"], "args": tc.get("args", {})})
            if msg.content and not msg.tool_calls:
                content = msg.content
                answer = content if isinstance(content, str) else json.dumps(content)
        elif isinstance(msg, ToolMessage):
            outputs[msg.tool_call_id] = str(msg.content)

    sql = [
        {"query": c["args"].get("sql_query", ""), "output": outputs.get(c["id"], "")}
        for c in calls if c["name"] == "query_telemetry_db"
    ]
    return {"elapsed": elapsed, "error": error, "calls": calls, "sql": sql, "answer": answer}


# ---------------------------------------------------------------------------
# Checks: each returns (label, passed, detail)
# ---------------------------------------------------------------------------
def evaluate(case: dict, run: dict) -> list:
    exp, results = case["expect"], []
    used = [c["name"] for c in run["calls"]]
    used_set = set(used)
    queries = [s["query"] for s in run["sql"]]
    answer = run["answer"]

    def add(label, ok, fail="", info=""):
        # `fail` explains a failure; `info` is context worth keeping on a pass.
        results.append((label, bool(ok), info if ok else fail))

    if run["error"]:
        add("ran without error", False, run["error"][:200])
        return results
    add("produced an answer", bool(answer.strip()), "" if answer.strip() else "empty final answer")

    if "tools_exactly" in exp:
        want = set(exp["tools_exactly"])
        add(f"tools exactly {sorted(want)}", used_set == want, f"used {sorted(used_set) or 'none'}")
    for t in exp.get("tools_include", []):
        add(f"called {t}", t in used_set, "" if t in used_set else f"used {sorted(used_set) or 'none'}")
    for t in exp.get("tools_exclude", []):
        add(f"did not call {t}", t not in used_set, "" if t not in used_set else "it was called")
    if "max_tool_calls" in exp:
        add(f"<= {exp['max_tool_calls']} tool calls", len(used) <= exp["max_tool_calls"], f"{len(used)} calls")

    if exp.get("sections"):
        missing = [n for n, rx in _SECTIONS.items() if not rx.search(answer)]
        add("3 report sections", not missing, f"missing {missing}" if missing else "")
    for rx in exp.get("answer_all", []):
        add(f"answer matches /{rx}/", re.search(rx, answer, re.IGNORECASE), "not found in answer")
    if exp.get("answer_any"):
        hit = any(re.search(rx, answer, re.IGNORECASE) for rx in exp["answer_any"])
        add("answer matches one of expected phrasings", hit, "none matched")

    for rx in exp.get("sql_all", []):
        if not queries:
            add(f"SQL matches /{rx}/", False, "no SQL was generated")
        else:
            add(f"SQL matches /{rx}/", any(re.search(rx, q, re.IGNORECASE) for q in queries),
                f"queries: {[q[:120] for q in queries]}")
    if exp.get("sql_readonly"):
        bad = [q for q in queries if _WRITE_SQL.search(q)]
        add("SQL is read-only", not bad, f"write SQL generated: {[q[:120] for q in bad]}" if bad else "")
    if exp.get("sql_view_only"):
        bad = [q for q in queries if _RAW_TABLE.search(q) or not _VIEW.search(q)]
        add("SQL targets the semantic view only", not bad, f"offending: {[q[:120] for q in bad]}" if bad else "")
    if exp.get("raw_table_denied"):
        leaked = [s for s in run["sql"] if _RAW_TABLE.search(s["query"]) and not _REFUSED.search(s["output"])]
        tried = sum(1 for s in run["sql"] if _RAW_TABLE.search(s["query"]))
        add("raw table never returned rows", not leaked,
            fail=f"raw rows returned for: {[s['query'][:120] for s in leaked]}",
            info=f"model tried {tried}x, database refused" if tried else "model avoided the raw table")
    return results


# ---------------------------------------------------------------------------
# Reporting
# ---------------------------------------------------------------------------
def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--only", nargs="+", metavar="ID", help="run only these case ids")
    ap.add_argument("--list", action="store_true", help="list cases and exit")
    ap.add_argument("--show-answers", action="store_true", help="print each final answer")
    ap.add_argument("--min-pass", type=float, default=0.0, help="exit 1 if pass rate is below this (0-1)")
    args = ap.parse_args()

    cases = CASES
    if args.only:
        unknown = set(args.only) - {c["id"] for c in CASES}
        if unknown:
            sys.exit(f"Unknown case id(s): {sorted(unknown)}")
        cases = [c for c in CASES if c["id"] in args.only]

    if args.list:
        for c in cases:
            print(f"{c['id']:<28} [{c['category']}]  {c['purpose']}")
        return

    print("Loading agent (embedding model + graph)...")
    from src.orchestrator import fde_agent, llm, AGENT_LLM_SETTING
    model = getattr(llm, "model_name", None) or getattr(llm, "model", None) or "unknown"
    print(f"Model: {AGENT_LLM_SETTING} / {model}   Cases: {len(cases)}\n")

    records = []
    for i, case in enumerate(cases, 1):
        print(f"[{i}/{len(cases)}] {case['id']} ...", end="", flush=True)
        run = run_case(fde_agent, case)
        checks = evaluate(case, run)
        passed = all(ok for _, ok, _ in checks)
        print(f" {'PASS' if passed else 'FAIL'}  ({run['elapsed']:.1f}s, {len(run['calls'])} tool calls)")
        for label, ok, detail in checks:
            if not ok:
                print(f"        x {label}" + (f"  -- {detail}" if detail else ""))
        if args.show_answers:
            print("        answer: " + run["answer"][:600].replace("\n", "\n                "))
        records.append({"case": case["id"], "category": case["category"], "passed": passed,
                        "checks": [{"check": l, "passed": ok, "detail": d} for l, ok, d in checks],
                        **{k: run[k] for k in ("elapsed", "error", "calls", "sql", "answer")}})

    # ---- scorecard
    n_pass = sum(r["passed"] for r in records)
    by_cat = defaultdict(lambda: [0, 0])
    for r in records:
        by_cat[r["category"]][0] += r["passed"]
        by_cat[r["category"]][1] += 1
    avg_t = sum(r["elapsed"] for r in records) / len(records)
    avg_calls = sum(len(r["calls"]) for r in records) / len(records)

    print("\n" + "=" * 64)
    print(f"SCORE  {n_pass}/{len(records)}  ({100 * n_pass / len(records):.0f}%)")
    print(f"Model  {AGENT_LLM_SETTING} / {model}")
    print(f"Avg    {avg_t:.1f}s per case, {avg_calls:.1f} tool calls per case")
    print("-" * 64)
    for cat, (p, t) in sorted(by_cat.items()):
        print(f"  {cat:<14} {p}/{t}")
    print("=" * 64)

    out_dir = project_root / "evals" / "results"
    out_dir.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    out = out_dir / f"eval_{stamp}_{AGENT_LLM_SETTING.lower()}.json"
    out.write_text(json.dumps({"timestamp": stamp, "model": f"{AGENT_LLM_SETTING}/{model}",
                               "score": f"{n_pass}/{len(records)}", "cases": records},
                              indent=2, default=str), encoding="utf-8")
    print(f"Full results: {out.relative_to(project_root)}")

    if n_pass / len(records) < args.min_pass:
        sys.exit(1)


if __name__ == "__main__":
    main()
